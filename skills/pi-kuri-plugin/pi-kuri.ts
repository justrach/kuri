/**
 * Wraps defineTool to give `execute` a typed `params` argument.
 * The type is inferred from the TypeBox schema via the `S` generic.
 */
function kuriTool<S extends ReturnType<typeof Type.Object>>(
  def: Omit<Parameters<typeof defineTool>[0], "parameters" | "execute"> & {
    parameters: S;
    execute: (
      toolCallId: string,
      params: Record<string, unknown>,
      signal: AbortSignal,
      onUpdate: (update: unknown) => void,
    ) => Promise<unknown> | unknown;
  },
) {
  return defineTool(def);
}

