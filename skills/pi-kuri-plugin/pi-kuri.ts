    "",
    "Preferred: use a page name from .sandcastle/site-manifest.yaml:",
    '  kuri_screenshot_site page="alert-log"',
    '  kuri_screenshot_site page="dashboard"',
    "",
    "Also valid: use an explicit simulator URL when the ticket needs a per-worktree server:",
    '  kuri_screenshot_site url="$(sandstate sim-url KEY)/indexWEB-ODAS.php#alert-log"',
      "",
