const kuriTextTool = kuriTool({
  name: "kuri_text",
  label: "Extract Page Text",
  description: "Extract plain text from the current page. Falls back to aria-labels and visible text if raw text is empty.",
  promptSnippet: "Extract page text",
  promptGuidelines: [
    "On JS-heavy SPAs, kuri_text may return empty string. The tool auto-falls back to aria-label extraction.",
    "If the result still seems sparse, try kuri_snap to see visible interactive elements.",
  ],
  parameters: Type.Object({
    tab_id: Type.Optional(Type.String({ description: "Optional explicit tab ID." })),
  }),
  execute: async (_toolCallId, params, _signal, _onUpdate) => {
    const query: Record<string, string> = {};
    if (params.tab_id) query.tab_id = String(params.tab_id);
    let rawText = await kuriFetchTextWithRetry("/text", query);
    let text = rawText;
    // Parse the JSON response to check if the extracted value is actually empty
    try {
      const parsed = JSON.parse(rawText);
      const extractedValue = parsed?.result?.result?.value || parsed?.result?.value || "";
      if (extractedValue && String(extractedValue).trim()) {
        text = String(extractedValue);
      } else {
        // Value is empty — trigger fallback
        text = "";
      }
    } catch {
      // Not JSON, use raw
    }
    // If extracted text is empty or whitespace-only, fall back to aria-labels
    // and visible leaf text via evaluate
    if (!text || !text.trim()) {
      try {
        const evalQuery: Record<string, string> = {
          expression: [
            "(function(){",
            "  var t=[];",
            "  var els=document.querySelectorAll('[aria-label],[role],a,button');",
            "  for(var i=0;i<els.length;i++){",
            "    var label=els[i].getAttribute('aria-label');",
            "    if(label&&label.trim()) t.push('['+els[i].tagName+'] '+label.trim().slice(0,120));",
            "  }",
            "  return t.length ? t.join('\\n') : document.title;",
            "  })()",
          ].join(""),
        };
        if (params.tab_id) evalQuery.tab_id = String(params.tab_id);
        const evalResult = await kuriFetchTextWithRetry("/evaluate", evalQuery);
        const parsed = JSON.parse(evalResult);
        const extracted = parsed?.result?.result?.value || parsed?.result?.value || "";
        if (extracted && String(extracted).trim()) {
          text = "[aria-label fallback]\n" + String(extracted);
        }
      } catch {
        // fallback failed — return original empty result
      }
    }
    return { content: [{ type: "text" as const, text }] };
  },
});

