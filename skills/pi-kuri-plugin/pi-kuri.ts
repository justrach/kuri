// ── Configuration helpers ─────────────────────────────────────────────────

function kuriBaseUrl(): string {
  return process.env.KURI_BASE_URL || "http://127.0.0.1:8080";
}

function kuriSession(): string {
  return process.env.KURI_SESSION || "pi-kuri-session";
}

function kuriAuthToken(): string | undefined {
  // 1. Try explicit env vars
  if (process.env.KURI_SECRET) return process.env.KURI_SECRET;
  if (process.env.KURI_API_TOKEN) return process.env.KURI_API_TOKEN;
  // 2. Read from api.token file (auto-generated by new Kuri builds)
  try {
    const homedir = process.env.HOME || process.env.HOMEPATH || "";
    return readFileSync(`${homedir}/.kuri/api.token`, "utf-8").trim();
  } catch {
    return undefined;
  }
}

function kuriHeaders(): Record<string, string> {
  const headers: Record<string, string> = {
    "X-Kuri-Session": kuriSession(),
    "Accept": "application/json",
  };
  const token = kuriAuthToken();
  if (token) {
    headers["Authorization"] = `Bearer ${token}`;
  }
  return headers;
}

function parseSiteScalar(value: string): string {
  const clean = value.trim().replace(/\s+#.*$/, "").trim();
  if ((clean.startsWith('"') && clean.endsWith('"')) || (clean.startsWith("'") && clean.endsWith("'"))) {
    return clean.slice(1, -1);
  }
  return clean;
}

function readSiteManifest(projectRoot: string): any {
  const manifestPath = path.join(projectRoot, ".sandcastle", "site-manifest.yaml");
  const raw = readFileSync(manifestPath, "utf-8");
  const manifest: any = { pages: {}, auth: {}, kuri: {} };
  let section = "";
  let pageName = "";
  for (const line of raw.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const top = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (top) {
      section = top[1];
      pageName = "";
      if (top[2]) manifest[section] = parseSiteScalar(top[2]);
      else if (section === "pages") manifest.pages = manifest.pages || {};
      else if (section === "auth") manifest.auth = manifest.auth || {};
      else if (section === "kuri") manifest.kuri = manifest.kuri || {};
      continue;
    }
    const nested = line.match(/^\s{2}([A-Za-z0-9_-]+):\s*(.*)$/);
    if (nested && section === "pages") {
      pageName = nested[1];
      manifest.pages[pageName] = nested[2] ? { url: parseSiteScalar(nested[2]) } : {};
      continue;
    }
    if (nested && (section === "auth" || section === "kuri")) {
      manifest[section][nested[1]] = parseSiteScalar(nested[2]);
      continue;
    }
    const pageField = line.match(/^\s{4}([A-Za-z0-9_-]+):\s*(.*)$/);
    if (pageField && section === "pages" && pageName) {
      manifest.pages[pageName][pageField[1]] = parseSiteScalar(pageField[2]);
    }
  }
  return manifest;
}

async function kuriFetch(path: string, query: Record<string, string> = {}): Promise<Response> {
  const base = kuriBaseUrl().replace(/\/+$/, "");
  const params = new URLSearchParams(query).toString();
  const url = `${base}${path}${params ? `?${params}` : ""}`;
  return fetch(url, { headers: kuriHeaders(), signal: AbortSignal.timeout(30_000) });
}

async function kuriFetchText(path: string, query: Record<string, string> = {}): Promise<string> {
  const resp = await kuriFetch(path, query);
  if (!resp.ok) {
    const body = await resp.text().catch(() => "");
    throw new Error(`Kuri ${path}: ${resp.status} ${resp.statusText} — ${body.slice(0, 200)}`);
  }
  return resp.text();
}

/**
 * Retry wrapper for CDP-fragile endpoints (page/info, screenshot, evaluate, markdown, etc.).
 * Retries up to maxRetries times with 1s exponential backoff on 502 (CDP failure).
 */
async function kuriFetchTextWithRetry(path: string, query: Record<string, string> = {}, maxRetries = 2): Promise<string> {
  let lastError: Error | null = null;
  for (let attempt = 0; attempt <= maxRetries; attempt++) {
    try {
      return await kuriFetchText(path, query);
    } catch (err: any) {
      const isCdpFailure = err.message?.includes("502") || err.message?.includes("CDP");
      if (isCdpFailure && attempt < maxRetries) {
        lastError = err;
        const delay = (attempt + 1) * 1000;
        await new Promise(r => setTimeout(r, delay));
        continue;
      }
      throw err;
    }
  }
  throw lastError || new Error(`Kuri ${path}: max retries exceeded`);
}

/**
 * Resolve the current session tab ID by calling /page/info.
 * Returns the tab_id string or throws if unavailable.
 */
async function resolveSessionTabId(): Promise<string> {
  const infoText = await kuriFetchTextWithRetry("/page/info", {});
  const info = JSON.parse(infoText);
  if (info.tab_id) return String(info.tab_id);
  throw new Error("Could not resolve current session tab ID");
}

function singleQuotedJsString(value: string): string {
  return `'${String(value).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\r/g, "\\r").replace(/\n/g, "\\n")}'`;
}

function loginPageWarning(pageInfo: any, text: string, expectedUrl: string): string {
  const finalUrl = String(pageInfo?.url || "");
  const title = String(pageInfo?.title || "");
  const lowerText = String(text || "").toLowerCase();
  const compactText = lowerText.replace(/\s+/g, " ").trim();
  const hasLoginAction = /\b(log\s*in|login|sign\s*in|authenticate)\b/.test(`${title} ${compactText}`);
  const urlLooksLogin = /\/login\b|login\.php|auth|authenticate/i.test(finalUrl);
  const titleLooksLogin = /\b(authenticate|login|sign in)\b/i.test(title);
  let expectedHash = "";
  let finalHash = "";
  try { expectedHash = new URL(expectedUrl).hash || ""; } catch { /* ignore */ }
  try { finalHash = new URL(finalUrl).hash || ""; } catch { /* ignore */ }
  const hashMismatch = Boolean(expectedHash && finalHash && expectedHash !== finalHash);
  const littleContent = compactText.length > 0 && compactText.length < 500;
  if ((urlLooksLogin || titleLooksLogin || hasLoginAction) && (littleContent || hashMismatch || urlLooksLogin || titleLooksLogin)) {
    return "There is strong evidence this capture may be an unauthenticated login page: little page content and login/authentication signals were detected. The reviewer should verify the provided screenshot is for the correct page.";
  }
  return "";
}

async function checkKuriHealth(): Promise<boolean> {
  try {
    const resp = await kuriFetch("/health");
    return resp.ok;
  } catch {
    return false;
  }
}

