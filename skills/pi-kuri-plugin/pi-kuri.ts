function isDuplicateToolConflict(error: unknown): boolean {
  return error instanceof Error && !!error.message?.includes("already defined");
}

async function cmdKuriStart(_args: string, ctx: ExtensionCommandContext): Promise<void> {
  const ok = await checkKuriHealth();
  if (ok) {
    ctx.ui.notify("Kuri server is already running.");
    return;
  }
  ctx.ui.notify("Kuri is not running. Start it manually:\n  kuri\n\nOr with options:\n  PORT=8080 kuri");
}

async function cmdKuriHealth(_args: string, ctx: ExtensionCommandContext): Promise<void> {
  const ok = await checkKuriHealth();
  if (ok) {
    const resp = await kuriFetch("/health");
    const data = await resp.text();
    ctx.ui.notify(`Kuri server is running.\n${data.slice(0, 500)}`);
  } else {
    ctx.ui.notify("Kuri server is NOT running. Start it with: kuri");
  }
}

