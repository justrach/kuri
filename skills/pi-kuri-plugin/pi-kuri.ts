    const current = kuriAuthToken();
    if (current) {
      ctx.ui.notify(`Auth token: ${current.slice(0, 20)}...`);
    } else {
      ctx.ui.notify("No auth token found. Set via KURI_SECRET env var or ~/.kuri/api.token file.");
    }
